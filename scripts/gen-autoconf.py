#!/usr/bin/env python3
"""
BusyBox-style Kconfig parser & autoconf generator for larper-tools.
Supports:
  gen-autoconf.py defconfig     Config.in .config
  gen-autoconf.py allyesconfig  Config.in .config
  gen-autoconf.py allnoconfig   Config.in .config
  gen-autoconf.py sync          Config.in .config include/autoconf.h build/config.mk
"""

import os
import re
import sys


def parse_config_in(path):
    items = []
    cur = None
    in_help = False
    with open(path, "r", encoding="utf-8") as f:
        for raw in f:
            line = raw.rstrip("\n")
            stripped = line.strip()
            if in_help:
                if line.startswith("\t") or line.startswith("  ") or stripped == "":
                    continue
                in_help = False
            m = re.match(r"^config\s+([A-Z0-9_]+)\s*$", stripped)
            if m:
                if cur:
                    items.append(cur)
                cur = {"name": m.group(1), "default": "n", "prompt": m.group(1)}
                continue
            if cur is not None:
                bm = re.match(r'^bool\s+"([^"]+)"', stripped)
                if bm:
                    cur["prompt"] = bm.group(1)
                    continue
                dm = re.match(r"^default\s+(y|n)", stripped)
                if dm:
                    cur["default"] = dm.group(1)
                    continue
                if stripped == "help":
                    in_help = True
                    continue
    if cur:
        items.append(cur)
    return items


def read_dot_config(path):
    vals = {}
    if not os.path.exists(path):
        return vals
    with open(path, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            m = re.match(r"^CONFIG_([A-Z0-9_]+)=(y|n)$", line)
            if m:
                vals[m.group(1)] = m.group(2)
                continue
            m = re.match(r"^#\s*CONFIG_([A-Z0-9_]+)\s+is not set$", line)
            if m:
                vals[m.group(1)] = "n"
    return vals


def write_dot_config(path, items, vals):
    with open(path, "w", encoding="utf-8") as f:
        f.write("#\n# Automatically generated file; DO NOT EDIT.\n")
        f.write("# larper-tools Configuration\n#\n")
        for it in items:
            name = it["name"]
            v = vals.get(name, it["default"])
            if v == "y":
                f.write(f"CONFIG_{name}=y\n")
            else:
                f.write(f"# CONFIG_{name} is not set\n")


def write_outputs(items, vals, header_path, mk_path):
    os.makedirs(os.path.dirname(header_path), exist_ok=True)
    os.makedirs(os.path.dirname(mk_path), exist_ok=True)
    with open(header_path, "w", encoding="utf-8") as h:
        h.write("/* Automatically generated by scripts/gen-autoconf.py; DO NOT EDIT. */\n")
        h.write("#ifndef LARPER_AUTOCONF_H\n#define LARPER_AUTOCONF_H\n\n")
        for it in items:
            name = it["name"]
            if vals.get(name, it["default"]) == "y":
                h.write(f"#define CONFIG_{name} 1\n")
            else:
                h.write(f"/* #undef CONFIG_{name} */\n")
        h.write("\n#endif /* LARPER_AUTOCONF_H */\n")

    with open(mk_path, "w", encoding="utf-8") as m:
        m.write("# Automatically generated by scripts/gen-autoconf.py; DO NOT EDIT.\n")
        for it in items:
            name = it["name"]
            v = vals.get(name, it["default"])
            if v == "y":
                m.write(f"CONFIG_{name} := y\n")
            else:
                m.write(f"CONFIG_{name} := n\n")


def main():
    if len(sys.argv) < 4:
        print("Usage: gen-autoconf.py <defconfig|allyesconfig|allnoconfig|sync> Config.in .config [autoconf.h config.mk]", file=sys.stderr)
        sys.exit(1)

    mode = sys.argv[1]
    config_in = sys.argv[2]
    dot_config = sys.argv[3]
    items = parse_config_in(config_in)

    if mode == "defconfig":
        vals = {it["name"]: it["default"] for it in items}
        write_dot_config(dot_config, items, vals)
        print(f"Wrote default configuration to {dot_config}")
    elif mode == "allyesconfig":
        vals = {it["name"]: "y" for it in items}
        write_dot_config(dot_config, items, vals)
        print(f"Wrote allyes configuration to {dot_config}")
    elif mode == "allnoconfig":
        vals = {it["name"]: "n" for it in items}
        write_dot_config(dot_config, items, vals)
        print(f"Wrote allno configuration to {dot_config}")
    elif mode == "sync":
        if len(sys.argv) < 6:
            sys.exit(1)
        vals = read_dot_config(dot_config)
        if not vals:
            vals = {it["name"]: it["default"] for it in items}
            write_dot_config(dot_config, items, vals)
        write_outputs(items, vals, sys.argv[4], sys.argv[5])
    else:
        print(f"Unknown mode: {mode}", file=sys.stderr)
        sys.exit(1)


if __name__ == "__main__":
    main()
